const DICTS: Record<Lang, Dict> = { th, en, zh, ja, ko };

function isLang(v: unknown): v is Lang {
  return v === 'th' || v === 'en' || v === 'zh' || v === 'ja' || v === 'ko';
}

function readLang(): Lang {
  try {
    const v = window.localStorage.getItem(KEY);
    if (isLang(v)) return v;
  } catch {
    // ที่เก็บข้อมูลถูกปิด — ใช้ภาษาไทย
  }
  return 'th';
}

let current: Lang = typeof window === 'undefined' ? 'th' : readLang();
const listeners = new Set<(l: Lang) => void>();

function applyHtmlLang(l: Lang) {
  if (typeof document !== 'undefined') document.documentElement.lang = l;
}
applyHtmlLang(current);

export function setLang(l: Lang) {
  current = l;
  try {
    window.localStorage.setItem(KEY, l);
  } catch {
    // ไม่จำก็ได้
  }
  applyHtmlLang(l);
  listeners.forEach((fn) => fn(l));
}

export function translate(l: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = DICTS[l][key] ?? th[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function localeOf(l: Lang): string {
  return LANGS.find((x) => x.id === l)?.locale ?? 'th-TH';
}

/** ภาษาปัจจุบัน + ฟังก์ชันแปล; ทุกคอมโพเนนต์ที่ใช้ hook นี้ render ใหม่เมื่อเปลี่ยนภาษา */
export function useLang() {
  const [lang, setState] = useState<Lang>(current);
  useEffect(() => {
    listeners.add(setState);
    setState(current);
    return () => { listeners.delete(setState); };
  }, []);
  const t = (key: string, vars?: Record<string, string | number>) => translate(lang, key, vars);
  return { lang, setLang, t, locale: localeOf(lang) };
}
