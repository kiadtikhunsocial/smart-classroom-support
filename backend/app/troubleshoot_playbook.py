_EMOJI_RE = re.compile(
    "[\U0001F300-\U0001FAFF\U0001F1E6-\U0001F1FF\u2600-\u27BF\uFE0F\u2B00-\u2BFF]"
)


def _norm(text) -> str:
    return " ".join(str(text or "").lower().split())


def _hits(hay: str, keys) -> int:
    return sum(1 for k in keys if k and k in hay)


def looks_like_problem(text: str) -> bool:
    """ข้อความนี้ดูเหมือนการแจ้งปัญหาอุปกรณ์หรือไม่

    ต้องมีคำบ่งชี้อาการเสียจริง — การเอ่ยชื่ออุปกรณ์เพียงอย่างเดียวไม่นับ
    (มิฉะนั้นคำถามขาย เช่น "สนใจซื้อ AiBoard" จะถูกดึงเข้า flow แจ้งซ่อม)
    """
    hay = _norm(text)
    if not hay:
        return False
    if not _hits(hay, PROBLEM_WORDS):
        return False
    if _hits(hay, COMMERCE_WORDS) and not _hits(hay, REPAIR_WORDS):
        return False
    return True


def find_playbook(text: str, device_hint: str = "", allow_generic: bool = True):
    """เลือก playbook ที่ตรงกับข้อความ/อุปกรณ์ที่ผู้ใช้บอก

    ให้คะแนน: อุปกรณ์ตรง 2/คำ, อาการตรง 3/คำ, ตรงทั้งคู่ +4
    คืน None ถ้าไม่เข้าเกณฑ์และไม่อนุญาต generic
    """
    hay = _norm(f"{text} {device_hint}")
    if not hay:
        return None
    commercial = bool(_hits(hay, COMMERCE_WORDS)) and not _hits(hay, REPAIR_WORDS)
    best = None
    best_score = 0
    best_symptoms = 0
    for pb in PLAYBOOKS:
        d = _hits(hay, pb.device_keys)
        s = _hits(hay, pb.symptom_keys)
        if not d and not s:
            continue
        score = d * 2 + s * 3 + (4 if d and s else 0)
        if score > best_score:
            best, best_score, best_symptoms = pb, score, s
    # ถามซื้อ/ถามราคาโดยไม่มีอาการเสีย → ปล่อยให้ flow ขายจัดการ ไม่ใช่แจ้งซ่อม
    if best is not None and best_score >= 3 and not (commercial and not best_symptoms):
        return best
    if allow_generic and looks_like_problem(hay):
        return GENERIC
    return None


def playbook_steps(text: str, device_hint: str = "") -> list:
    """คืนเฉพาะรายการขั้นตอน (ใช้ส่งต่อให้ explain_steps ของ gemini_service ได้)"""
    pb = find_playbook(text, device_hint)
    return list(pb.steps) if pb else []


def format_playbook_reply(pb, deep: bool = False, max_steps: int = 4) -> str:
    """ทำคำตอบสั้น: เกริ่นสาเหตุ 1 บรรทัด + ขั้นตอนมีเลข + ปิดท้ายให้ตอบกลับ"""
    if pb is None:
        return ""
    steps = list(pb.deep) if (deep and pb.deep) else list(pb.steps)
    lines = []
    if deep and pb.deep:
        lines.append("ยังไม่หายก็ไม่เป็นไรค่ะ ขอลองแยกจุดเสียอีกนิดนะคะ")
    elif pb.cause:
        lines.append(pb.cause)
    for i, step in enumerate(steps[:max_steps], 1):
        lines.append(f"{i}. {step}")
    lines.append("ลองแล้วบอกได้เลยนะคะว่า 'หายแล้ว' หรือ 'ยังไม่หาย' ค่ะ")
    return "\n".join(lines)


def condense(text: str, max_lines: int = 8, max_emoji: int = 1) -> str:
    """ย่อคำตอบให้อ่านง่ายในแชท: ตัดบรรทัดว่างซ้ำ บรรทัดซ้ำ และอีโมจิที่เกิน"""
    if not text:
        return ""
    seen = set()
    lines = []
    for raw in str(text).splitlines():
        line = raw.rstrip()
        key = line.strip()
        if not key:
            if lines and lines[-1] != "":
                lines.append("")
            continue
        if key in seen:
            continue
        seen.add(key)
        lines.append(line)
    while lines and lines[-1] == "":
        lines.pop()
    if len(lines) > max_lines:
        lines = lines[:max_lines]
    out = "\n".join(lines)
    if max_emoji >= 0:
        kept = 0

        def _repl(match):
            nonlocal kept
            if kept < max_emoji:
                kept += 1
                return match.group(0)
            return ""

        out = _EMOJI_RE.sub(_repl, out)
        out = re.sub(r"[ \t]{2,}", " ", out)
        out = "\n".join(line.rstrip() for line in out.splitlines())
    return out.strip()